import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DEMO_AGENT, DEMO_DAYS, DEMO_HOME, DEMO_PLUGIN, DEMO_PROJECTS, DEMO_SESSIONS, LEGACY_SERVER, LEGACY_SERVER_REMOVED_DAYS_AGO, MAIN_MODEL, SECONDARY_MODEL, USER_SKILLS } from './demo-scenario.ts'
import type { DemoRecord } from './demo-thread.ts'
import { generateDemoSession } from './generate-demo-session.ts'
import { createSeededRandom } from './seeded-random.ts'

const DAY = 24 * 60 * 60 * 1000
const HOUR = 60 * 60 * 1000
const DEMO_MARKER_FILE = '.token-audit-demo'
const SEED = 20_261_109

export type DemoWorkspace = {
  transcriptsDirectory: string
  claudeHome: string
  claudeJsonPath: string
  dataDirectory: string
}

function writeJson(path: string, value: unknown): void {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`)
}

function writeJsonl(path: string, records: DemoRecord[]): void {
  writeFileSync(path, `${records.map((record) => JSON.stringify(record)).join('\n')}\n`)
}

function resetDirectory(root: string): void {
  if (existsSync(root)) {
    if (!existsSync(join(root, DEMO_MARKER_FILE))) throw new Error(`${root} exists and is not a demo workspace: refusing to overwrite it`)
    rmSync(root, { recursive: true })
  }
  mkdirSync(root, { recursive: true })
  writeFileSync(join(root, DEMO_MARKER_FILE), 'Generated by `pnpm demo`. Safe to delete.\n')
}

function writeClaudeConfig(workspace: DemoWorkspace): void {
  mkdirSync(join(workspace.claudeHome, 'agents'), { recursive: true })
  writeJson(join(workspace.claudeHome, 'settings.json'), { enabledPlugins: { [DEMO_PLUGIN.id]: true } })
  for (const skill of USER_SKILLS) {
    mkdirSync(join(workspace.claudeHome, 'skills', skill.name), { recursive: true })
    writeFileSync(join(workspace.claudeHome, 'skills', skill.name, 'SKILL.md'), `---\nname: ${skill.name}\ndescription: Demo skill\n---\n`)
  }
  writeFileSync(join(workspace.claudeHome, 'agents', `${DEMO_AGENT.type}.md`), `---\nname: ${DEMO_AGENT.type}\ndescription: ${DEMO_AGENT.description}\n---\n\nReview the diff and report blocking issues.\n`)
  writeJson(workspace.claudeJsonPath, {
    mcpServers: {
      'browser-devtools': { type: 'stdio', command: 'npx', args: ['browser-devtools-mcp'] },
      jira: { type: 'http', url: 'https://jira.example.com/mcp' },
      'postgres-explorer': { type: 'stdio', command: 'npx', args: ['postgres-explorer-mcp'] },
    },
  })
}

function writeAppliedAction(workspace: DemoWorkspace, appliedAt: number): void {
  mkdirSync(workspace.dataDirectory, { recursive: true })
  const markerId = '00000000-0000-4000-8000-000000000001'
  const title = `Retirer le serveur MCP « ${LEGACY_SERVER.name} »`
  writeJson(join(workspace.dataDirectory, 'markers.json'), [{ id: markerId, at: appliedAt, label: `Action : ${title}`, project: null, createdAt: appliedAt }])
  writeJson(join(workspace.dataDirectory, 'actions.json'), [
    {
      id: '00000000-0000-4000-8000-000000000002',
      key: `disable-mcp-server:${LEGACY_SERVER.name}`,
      kind: 'disable-mcp-server',
      title,
      project: null,
      estimatedMonthlySavingUSD: 26,
      appliedAt,
      markerId,
      undo: { kind: 'mcp-server-config', serverName: LEGACY_SERVER.name, serverConfig: { type: 'stdio', command: 'npx', args: ['legacy-search-mcp'] } },
      undoneAt: null,
      verification: { kind: 'footprint', footprint: { kind: 'mcp-server', serverName: LEGACY_SERVER.name }, label: `outils du serveur « ${LEGACY_SERVER.name} »` },
    },
  ])
}

function sessionStart(index: number, now: number, random: ReturnType<typeof createSeededRandom>): number {
  const day = Math.floor((index / DEMO_SESSIONS) * DEMO_DAYS)
  const startOfDay = now - (DEMO_DAYS - day) * DAY
  return Math.min(startOfDay + random.between(8, 19) * HOUR, now - 10 * HOUR)
}

export function generateDemoWorkspace(root: string, now = Date.now()): DemoWorkspace {
  resetDirectory(root)
  const workspace: DemoWorkspace = {
    transcriptsDirectory: join(root, 'projects'),
    claudeHome: join(root, 'claude-home'),
    claudeJsonPath: join(root, 'claude.json'),
    dataDirectory: join(root, 'data'),
  }
  writeClaudeConfig(workspace)
  const legacyRemovedAt = now - LEGACY_SERVER_REMOVED_DAYS_AGO * DAY
  writeAppliedAction(workspace, legacyRemovedAt)
  const random = createSeededRandom(SEED)
  for (let index = 0; index < DEMO_SESSIONS; index += 1) {
    const project = random.chance(0.55) ? DEMO_PROJECTS[0]! : random.chance(0.6) ? DEMO_PROJECTS[1]! : DEMO_PROJECTS[2]!
    const startedAt = sessionStart(index, now, random)
    const sessionId = `demo${String(index).padStart(4, '0')}-0000-4000-8000-${String(SEED + index).padStart(12, '0')}`
    const session = generateDemoSession({
      sessionId,
      project,
      startedAt,
      model: random.chance(0.8) ? MAIN_MODEL : SECONDARY_MODEL,
      includesLegacyServer: startedAt < legacyRemovedAt,
      random,
    })
    const projectDirectory = join(workspace.transcriptsDirectory, `-Users-demo-${project.cwd.slice(DEMO_HOME.length + 1).replace(/\//g, '-')}`)
    mkdirSync(projectDirectory, { recursive: true })
    writeJsonl(join(projectDirectory, `${sessionId}.jsonl`), session.records)
    if (session.subagents.length === 0) continue
    const subagentsDirectory = join(projectDirectory, sessionId, 'subagents')
    mkdirSync(subagentsDirectory, { recursive: true })
    for (const subagent of session.subagents) {
      writeJsonl(join(subagentsDirectory, `agent-${subagent.agentId}.jsonl`), subagent.records)
      writeJson(join(subagentsDirectory, `agent-${subagent.agentId}.meta.json`), subagent.meta)
    }
  }
  return workspace
}
